cmd({
  pattern: "textgen",
  alias: ["emojitext", "redwhite"],
  react: "🪶",
  desc: "Convert text to Red and White Emoji Art",
  category: "converter",
  filename: __filename
}, async (conn, mek, m, { from, q, reply }) => {

  try {
    if (!q) {
      return reply("⚠️ *Please provide a word!*\n\n*Example:* `.textgen HIRUKA`");
    }

    // Limit text length to prevent chat lag
    if (q.length > 8) {
      return reply("❌ *Maximum character limit is 8!*");
    }

    const result = generateEmojiText(q);

    if (result) {
      await conn.sendMessage(from, { text: result }, { quoted: fakevCard });
    } else {
      await reply("❌ Unsupported characters provided.");
    }

  } catch (error) {
    console.error("❌ Error in textgen plugin:", error);
    reply("*Error generating emoji text*");
  }

});
