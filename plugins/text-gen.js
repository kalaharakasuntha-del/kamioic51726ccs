const COLORS = {
    blue: "🟦",
    red: "🟥",
    green: "🟩",
    orange: "🟧",
    pink: "🩷",
    purple: "🟪",
    lightblue: "🩵"
};

cmd({
    pattern: "textgen",
    alias: ["pixeltext", "blocktext"],
    desc: "Generate colored pixel text",
    category: "fun",
    use: ".textgen blue Hiruka",
    filename: __filename
}, async (conn, mek, m, { from, args, reply }) => {

    try {

        if (!args || args.length < 2) {
            return reply(
                "❌ *Usage:*\n\n" +
                "`.textgen blue Hiruka`\n\n" +
                "*Available Colors:*\n" +
                "🔵 blue\n" +
                "🔴 red\n" +
                "🟢 green\n" +
                "🟠 orange\n" +
                "🩷 pink\n" +
                "🟣 purple\n" +
                "🩵 lightblue"
            );
        }

        const colorName = args[0].toLowerCase();
        const text = args.slice(1).join(" ").toUpperCase();

        if (!COLORS[colorName]) {
            return reply(
                "❌ Invalid color!\n\n" +
                "Use one of:\n" +
                "🔵 blue\n" +
                "🔴 red\n" +
                "🟢 green\n" +
                "🟠 orange\n" +
                "🩷 pink\n" +
                "🟣 purple\n" +
                "🩵 lightblue"
            );
        }

        if (text.length > 15) {
            return reply("❌ Maximum 15 characters!");
        }

        const COLOR = COLORS[colorName];
        const WHITE = "⬜";

        const letters = text.split("");
        const output = [];

        for (let row = 0; row < 7; row++) {

            let line = "";

            for (const char of letters) {

                const pattern = FONT[char] || FONT[" "];

                for (const pixel of pattern[row]) {
                    line += pixel === "1" ? COLOR : WHITE;
                }

                // Space between letters
                line += WHITE;
            }

            output.push(line);
        }

        await conn.sendMessage(
            from,
            {
                text: output.join("\n")
            },
            {
                quoted: fakevCard
            }
        );

    } catch (error) {
        console.error("TEXTGEN ERROR:", error);
        reply("❌ Text generation failed!");
    }
});
