function generateEmojiText(text) {
    text = text.toUpperCase();
    let output = [];
    for (let char of text) {
        let pattern = FONT[char] || FONT[' '];
        if (pattern) {
            output.push(...pattern);
        }
    }
    return output.join('\n');
}

