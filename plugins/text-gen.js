cmd({
    pattern: "textgen",
    alias: ["pixeltext", "blocktext"],
    desc: "Generate 🟥⬜ pixel text",
    category: "fun",
    use: ".textgen HIRUKA",
    filename: __filename
}, async (conn, mek, m, { from, args, reply }) => {

    try {
        if (!args || args.length === 0) {
            return reply(
                "❌ Please enter a name!\n\n" +
                "Example:\n" +
                "`.textgen HIRUKA`"
            );
        }

        let text = args.join(" ").toUpperCase();

        // Limit text length to prevent huge messages
        if (text.length > 15) {
            return reply("❌ Maximum 15 characters only!");
        }

        let letters = text.split("");
        let output = [];

        // Generate each of the 7 rows
        for (let row = 0; row < 7; row++) {
            let line = "";

            for (let char of letters) {
                let pattern = FONT[char] || FONT[" "];

                for (let pixel of pattern[row]) {
                    line += pixel === "1" ? "🟥" : "⬜";
                }

                line += "⬜";
            }

            output.push(line);
        }

        let result = output.join("\n");

        await conn.sendMessage(from, {
            text: result
        }, {
            quoted: mek
        });

    } catch (e) {
        console.log("TEXTGEN ERROR:", e);
        reply("❌ Text generation failed!");
    }
});
